/** 이미 종류가 명시된 라벨. 저작이므로 덮지 않는다. */
const EXPLICIT = new Set(["melee", "ranged", "fist"]);

export function migrate(doc, ctx) {
  const plan = TARGETS[doc.name];
  if (!plan) return;

  for (const [channel, keys] of Object.entries(plan)) {
    const map = channel === "self" ? doc.system?.attributes : doc.system?.effect?.attributes;
    const seen = new Set();
    for (const row of Object.values(map || {})) {
      if (!row || typeof row !== "object") continue;
      const want = keys[row.key];
      if (!want) continue;
      seen.add(row.key);
      if (row.label === want) continue;
      if (EXPLICIT.has(row.label)) {
        ctx.log(`${channel}.${row.key} 가 이미 '${row.label}' 로 명시돼 있어 건너뛴다(기대: ${want})`);
        continue;
      }
      row.label = want;
      ctx.log(`${channel}.${row.key} 보정을 '${want}' 한정으로 명시`);
    }
    // 기대한 행이 없으면 조용히 넘기지 않는다 — 이름이 바뀌었거나 저작이 사라진 것이다.
    for (const key of Object.keys(keys)) {
      if (!seen.has(key)) ctx.log(`기대한 ${channel}.${key} 보정 행이 없다`);
    }
  }
}
