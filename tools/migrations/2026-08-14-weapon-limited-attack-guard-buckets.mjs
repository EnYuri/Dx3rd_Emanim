// 「맨손 한정」·「백병 한정」으로 저작돼야 할 공격력·가드치 보정을 실제 버킷으로 옮긴다.
//
// 이 행들은 전부 라벨이 `-`(전체)라 **모든 무기에 붙고 있었다.** 「당신의 맨손 공격력에
// +5」(불길한 나무열매)가 총·검에도 붙고, 「당신이 실행하는 백병공격의 공격력에 +6」
// (나찰)이 사격에도 붙는 식이다. 라벨을 무기 종류로 명시하면 actor.js 의
// `R.bucket(<키>, ['melee','ranged','fist'])` 가 그 종류에서만 세고, 데미지 산출은
// 공격에 실제로 쓴 무기(`resolveAttackBonuses`)·가드에 실제로 고른 무기
// (`getWeaponGuardBonus`)를 기준으로 그 몫을 꺼낸다.
//
// **가드치 버킷은 이 커밋에서 새로 생겼다.** 그전에는 `guard` 에 버킷 자체가 없어
// 「맨손의 가드치에 +3」(특수장갑의수 등)을 표현할 수단이 없었다.
//
// 대상은 이름을 명시한다. 「설명에 맨손이 있으면」 같은 술어로 잡으면 정반대인 문서까지
// 걸린다 — 《폼 체인지》·《No.40 기물술사》는 **맨손 이외**의 무기가 대상이다.
//
// ── 손대지 않는 것(표현할 버킷이 없어 수동으로 남긴다) ──────────────────────────
//   《피의 축복》   맨손 **및 《붉은 검》으로 작성한 무기** — 두 번째 항을 담을 자리가 없다.
//   《폼 체인지》   맨손 **이외**의 무기 중 **선택한 하나** — 부정 버킷도, 선택도 없다.
//   《No.40 기물술사》 맨손 **이외**의 무기에 의한 가드치 +5 — 같은 이유.
//   《암드 스카프》 이펙트로 작성·변경한 무기 — 무기 종류가 아니라 출처가 조건이다.
//   《No.46 달인》  지정 이펙트를 조합한 공격 — 무기 종류와 무관하므로 전체가 맞다.
// 《도약하는 발굽》의 「《일각귀》로 변경된 맨손이면 +[Lv×3]」 조건부 상향도 수동이다
// (백병 한정까지만 옮긴다 — 지금은 사격에도 붙고 있으므로 그것만으로 개선이다).

export const description = "맨손·백병 한정 공격력/가드치 보정을 무기 종류 버킷으로 명시";

/**
 * 문서 이름 → 그 문서에서 종류를 명시할 행. 원문 근거를 함께 적는다.
 * 한 문서가 두 키를 다 가진 경우(맨손의 공격력과 가드치에 각각 +N)가 있어 키별로 적는다.
 */
const TARGETS = {
  // ── 맨손 한정 ───────────────────────────────────────────────────────────────
  "붕괴의 고동":      { attack: "fist" },   // 당신의 맨손의 공격력에 +[Lv×2]
  "강신수화":         { attack: "fist" },   // 당신이 맨손을 사용하여 실행하는 공격의 공격력에 +[LV×2]
  "오리진 (애니멀)":  { attack: "fist" },   // 당신의 맨손 공격력에 +[LV×2]
  "불길한 나무열매":  { attack: "fist" },   // 당신의 맨손 공격력에 +5
  "수확자의 장갑":    { attack: "fist" },   // 이펙트를 조합한 맨손으로 공격하는 … 그 공격력에 +10
  "강인한 골격":      { attack: "fist", guard: "fist" },  // 맨손의 공격력과 가드치에 각각 +[LV+1]
  "근력 증가":        { attack: "fist", guard: "fist" },  // 당신의 맨손의 공격력/가드에 +3
  "특수장갑의수":     { attack: "fist", guard: "fist" },  // 맨손 공격력에 +4, 가드치에 +3
  "헬즈 월":          { guard: "fist" },    // 맨손의 가드치에 +【육체】

  // ── 백병 한정 ───────────────────────────────────────────────────────────────
  "No.38 나찰":       { attack: "melee" },  // 당신이 실행하는 백병공격의 공격력에 +6
  "도약하는 발굽":    { attack: "melee" }   // 다음에 당신이 백병공격할 때 공격력에 +[Lv×2]
};

/** 이미 종류가 명시된 라벨. 여기에 걸리면 저작이므로 덮지 않는다. */
const EXPLICIT = new Set(["melee", "ranged", "fist"]);

export function migrate(doc, ctx) {
  const plan = TARGETS[doc.name];
  if (!plan) return;

  const seen = new Set();
  // 자기 채널만 대상이다 — 위 문서들은 전부 자기 보정이고, 대상 채널에 같은 키가 있다면
  // 그것은 남에게 거는 다른 저작이므로 건드리면 안 된다.
  for (const row of Object.values(doc.system?.attributes || {})) {
    if (!row || typeof row !== "object") continue;
    const want = plan[row.key];
    if (!want) continue;
    seen.add(row.key);
    if (row.label === want) continue;
    if (EXPLICIT.has(row.label)) {
      ctx.log(`${row.key} 행이 이미 '${row.label}' 로 명시돼 있어 건너뛴다(기대: ${want})`);
      continue;
    }
    row.label = want;
    ctx.log(`${row.key} 보정을 '${want}' 한정으로 명시`);
  }

  // 기대한 행이 없으면 조용히 넘기지 않는다 — 이름이 바뀌었거나 저작이 사라진 것이다.
  for (const key of Object.keys(plan)) {
    if (!seen.has(key)) ctx.log(`기대한 ${key} 보정 행이 없다`);
  }
}
