// 일회용 기본 사용 횟수(세션 1회)를 싣는다.
const RETYPE = { items: { TSB: "once" } };

export function migrate(doc, ctx) {
  const saving = SAVING[ctx.pack]?.[doc.name];
  if (saving) {
    doc.system.saving ??= {};
    doc.system.saving.difficulty = saving[0];
    doc.system.saving.value = saving[1];
  }
  const exp = EXP[ctx.pack]?.[doc.name];
  if (exp !== undefined) doc.system.exp = exp;
  const retype = RETYPE[ctx.pack]?.[doc.name];
  if (retype) {
    doc.type = retype;
    doc.system.type = retype;
    doc.system.used = { state: 0, max: 1, level: false, disable: "session" };
  }
}
