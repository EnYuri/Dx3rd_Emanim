export function migrate(doc, ctx) {
  if (doc.type !== "effect") return;
  if (DUPLICATES[doc._id]) {
    ctx.delete();
    return;
  }
  const target = TARGET.get(doc.name);
  if (!target || doc.folder === target) return;
  doc.folder = target;
}
